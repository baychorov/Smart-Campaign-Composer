CREATE TABLE users (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   text        NOT NULL DEFAULT '',
    last_name    text        NOT NULL,
    email        text        NOT NULL UNIQUE,
    phone        text        NOT NULL UNIQUE,
    city         text        NOT NULL,
    age          smallint    NOT NULL CHECK (age BETWEEN 13 AND 100),
    sms_opt_in   boolean     NOT NULL,
    email_opt_in boolean     NOT NULL,
    created_at   timestamptz NOT NULL
);

CREATE INDEX users_city_idx ON users (city);

CREATE TABLE user_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    event_type  text        NOT NULL
        CHECK (event_type IN ('signup', 'product_view', 'add_to_cart', 'purchase')),
    occurred_at timestamptz NOT NULL
);

-- Serves EXISTS / NOT EXISTS lookups of the form
-- (user_id = ? AND event_type = ? AND occurred_at >= ?).
CREATE INDEX user_events_lookup_idx ON user_events (user_id, event_type, occurred_at);

CREATE TABLE campaigns (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brief          text        NOT NULL,
    status         text        NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'approved', 'sending', 'completed')),
    rule           jsonb,
    sms_text       text,
    email_subject  text,
    email_body     text,
    send_sms       boolean     NOT NULL DEFAULT false,
    send_email     boolean     NOT NULL DEFAULT false,
    partial_ack_at timestamptz,
    approved_at    timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now()
);

-- Queue and status record in one table (D-DB). The unique key is the
-- "same message" definition of D-DEDUP: campaign + person + channel.
CREATE TABLE deliveries (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id     bigint      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    user_id         bigint      NOT NULL REFERENCES users (id),
    channel         text        NOT NULL CHECK (channel IN ('sms', 'email')),
    status          text        NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'sent', 'failed', 'skipped')),
    attempts        integer     NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    locked_until    timestamptz,
    last_error      text,
    sent_at         timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (campaign_id, user_id, channel)
);

-- Worker claim query: unfinished rows of a channel ordered by due time.
CREATE INDEX deliveries_ready_idx ON deliveries (channel, next_attempt_at)
    WHERE status IN ('pending', 'sending');

